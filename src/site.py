# ---------------------------------------------------------------------------
# Formatação
# ---------------------------------------------------------------------------

_numero = formato.numero


def _data(d, idioma):
    if d is None:
        return "—"
    return d.strftime("%d/%m/%Y") if idioma == "pt" else d.strftime("%b %d, %Y")


def _classe(v, escuro=False):
    """Classe do delta. A barra lateral usa um par de cores próprio, porque
    o vermelho do conteúdo não tem contraste suficiente sobre o grafite."""
    prefixo = "s-" if escuro else ""
    if v is None or v == 0:
        return f"{prefixo}flat"
    return f"{prefixo}up" if v > 0 else f"{prefixo}down"


def _delta(valor, idioma, sufixo="%", escuro=False):
    """Variação com seta + número. A seta é a codificação não-cromática."""
    if valor is None:
        return f'<span class="{_classe(None, escuro)}">—</span>'
    seta = "▲" if valor > 0 else ("▼" if valor < 0 else "■")
    return (f'<span class="{_classe(valor, escuro)}">{seta} '
            f'{_numero(abs(valor), 2, idioma)}{sufixo}</span>')


def _esc(t):
    return html.escape(str(t), quote=True)


# ---------------------------------------------------------------------------
# Sparkline
# ---------------------------------------------------------------------------

def _sparkline(serie, positivo, largura=118, altura=30):
    """Linha de tendência de uma série, sem eixos nem rótulos.

    Série única, então nada de legenda; o valor de cada dia está na tabela,
    o que mantém o dado acessível sem depender do gráfico.
    """
    valores = [v for _, v in serie]
    if len(valores) < 2:
        return ""

    pad = 3
    minimo, maximo = min(valores), max(valores)
    span = (maximo - minimo) or 1
    passo = (largura - 2 * pad) / (len(valores) - 1)

    pontos = [
        (pad + i * passo,
         altura - pad - ((v - minimo) / span) * (altura - 2 * pad))
        for i, v in enumerate(valores)
    ]
    caminho = " ".join(f"{x:.1f},{y:.1f}" for x, y in pontos)
    cor = "var(--up-mark)" if positivo else "var(--down-mark)"
    fx, fy = pontos[-1]

    return (
        f'<svg class="spark" width="{largura}" height="{altura}" '
        f'viewBox="0 0 {largura} {altura}" role="img" aria-hidden="true">'
        f'<polyline points="{caminho}" fill="none" stroke="{cor}" '
        f'stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/>'
        f'<circle cx="{fx:.1f}" cy="{fy:.1f}" r="2.5" fill="{cor}"/>'
        f"</svg>"
    )


