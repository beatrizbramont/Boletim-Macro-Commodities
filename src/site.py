# Blocos
# ---------------------------------------------------------------------------

def _tiles_macro(contexto, idioma, t):
    if not contexto["macro"]:
        return f'<p class="vazio">{t["sem_dados"]}</p>'

    nome = "nome_pt" if idioma == "pt" else "nome_en"
    blocos = []
    for d in contexto["macro"].values():
        # Taxa move em pontos percentuais; cotação, em porcentagem.
        if d["tipo"] == "taxa":
            delta = _delta(d.get("var_dia_abs"), idioma, t["pp"])
        else:
            delta = _delta(d.get("var_dia_pct"), idioma)

        blocos.append(
            '<div class="tile">'
            f'<div class="rot">{_esc(d[nome])}</div>'
            f'<div class="val">{_numero(d["valor"], d["casas"], idioma)}'
            f'<span class="un">{_esc(d["unidade"])}</span></div>'
            f'<div class="delta">{delta}</div>'
            f'<div class="ref">{t["ref"]} {_data(d["data"], idioma)}</div>'
            "</div>"
        )
    return f'<div class="tiles">{"".join(blocos)}</div>'


def _tabela_commodities(contexto, idioma, t):
    if not contexto["commodities"]:
        return f'<p class="vazio">{t["sem_dados"]}</p>'

    nome = "nome_pt" if idioma == "pt" else "nome_en"
    unidade = "unidade_pt" if idioma == "pt" else "unidade_en"

    linhas = []
    for d in contexto["commodities"].values():
        spark = _sparkline(d.get("serie", []), (d.get("var_mes_pct") or 0) >= 0)
        linhas.append(
            "<tr>"
            f'<td class="ativo">{_esc(d[nome])}</td>'
            f'<td>{_numero(d["valor"], 2, idioma)}'
            f'<span class="un-cell">{_esc(d[unidade])}</span></td>'
            f'<td>{_delta(d.get("var_dia_pct"), idioma)}</td>'
            f'<td>{_delta(d.get("var_semana_pct"), idioma)}</td>'
            f'<td>{_delta(d.get("var_mes_pct"), idioma)}</td>'
            f"<td>{spark}</td>"
            "</tr>"
        )

    return (
        '<div class="tbl-wrap"><table>'
        "<thead><tr>"
        f'<th>{t["col_ativo"]}</th><th>{t["col_valor"]}</th>'
        f'<th>{t["col_dia"]}</th><th>{t["col_semana"]}</th>'
        f'<th>{t["col_mes"]}</th><th>{t["col_tendencia"]}</th>'
        "</tr></thead>"
        f'<tbody>{"".join(linhas)}</tbody>'
        "</table></div>"
    )


def _bloco_noticias(contexto, t):
    noticias = contexto.get("noticias") or []
    if not noticias:
        return ""
    itens = []
    for n in noticias[: config.MAX_NOTICIAS_SITE]:
        quando = n["publicado"].strftime("%d/%m %H:%M") if n.get("publicado") else ""
        itens.append(
            "<li>"
            f'<a href="{_esc(n["link"])}" target="_blank" rel="noopener">'
            f'{_esc(n["titulo"])}</a>'
            f'<div class="meta">{_esc(n["fonte"])}'
            f'{" · " + quando if quando else ""}</div>'
            "</li>"
        )
    return f'<h2>{t["secao_noticias"]}</h2><ul class="news">{"".join(itens)}</ul>'


# ---------------------------------------------------------------------------
# Página
# ---------------------------------------------------------------------------

def renderizar(contexto, narrativa, idioma, dias_historico=0):
    t = TEXTOS[idioma]
    lang_attr = "pt-BR" if idioma == "pt" else "en"

    manchete = _esc(narrativa.get("manchete") or t["titulo"])
    resumo = _esc(narrativa.get("resumo") or "")

    analise = "".join(f"<p>{_esc(p)}</p>" for p in narrativa.get("analise", []))
    bloco_analise = (
        f'<h2>{t["secao_analise"]}</h2><div class="analise">{analise}</div>'
        if analise else ""
    )

    destaques = "".join(f"<li>{_esc(d)}</li>" for d in narrativa.get("destaques", []))
    bloco_destaques = (
        f'<h2>{t["secao_destaques"]}</h2><ul class="lista">{destaques}</ul>'
        if destaques else ""
    )

    placar = t["placar"].format(**contexto["placar"])
    hist = (f' · {t["dias_hist"].format(n=dias_historico)}'
            if dias_historico > 1 else "")

    return f"""<!doctype html>
<html lang="{lang_attr}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{t["titulo"].replace("&amp;", "&")} — {_data(contexto["data_ref"], idioma)}</title>
<meta name="description" content="{manchete}">
<meta name="color-scheme" content="light dark">
<style>{CSS}</style>
</head>
<body>
<div class="wrap">

  <header class="top">
    <div>
      <h1>{t["titulo"]}</h1>
      <p class="sub">{t["subtitulo"]}</p>
    </div>
    <a class="lang" href="{t["href_alt"]}">{t["idioma_alt"]}</a>
  </header>

  <section class="hero">
    <p class="manchete">{manchete}</p>
    <p class="resumo">{resumo}</p>
    <div class="placar">{placar}{hist}</div>
  </section>

  <h2>{t["secao_macro"]}</h2>
  {_tiles_macro(contexto, idioma, t)}

  <h2>{t["secao_commodities"]}</h2>
  {_tabela_commodities(contexto, idioma, t)}

  {bloco_analise}
  {bloco_destaques}
  {_bloco_noticias(contexto, t)}

  <footer>
    <p><strong>{t["fontes"]}:</strong> {t["fontes_txt"]}</p>
    <p>{t["gerado"]}: {_esc(narrativa.get("gerado_por", "—"))} ·
       {t["atualizado"]}: {_data(contexto["gerado_em"], idioma)}</p>
    <p class="aviso">{t["aviso"]}</p>
  </footer>

</div>
</body>
</html>
"""


def publicar(contexto, narrativas, dias_historico=0):
    """Escreve docs/index.html (pt) e docs/en/index.html (en)."""
    config.DIR_SITE.mkdir(parents=True, exist_ok=True)
    (config.DIR_SITE / "en").mkdir(parents=True, exist_ok=True)

    caminhos = []
    for idioma in config.IDIOMAS:
        narrativa = narrativas.get(idioma, {})
        html_txt = renderizar(contexto, narrativa, idioma, dias_historico)
        destino = (config.DIR_SITE / "index.html" if idioma == "pt"
                   else config.DIR_SITE / "en" / "index.html")
        destino.write_text(html_txt, encoding="utf-8")
        caminhos.append(destino)
        log.info("site [%s] -> %s (%d KB)", idioma, destino.name,
                 len(html_txt) // 1024)

    # Impede o Jekyll do GitHub Pages de reprocessar o diretório.
    (config.DIR_SITE / ".nojekyll").write_text("", encoding="utf-8")
    return caminhos
