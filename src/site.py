def _metricas_barra(contexto, idioma, t):
    """Indicadores macro na barra lateral — cores próprias do fundo escuro."""
    if not contexto["macro"]:
        return ""

    nome = "nome_pt" if idioma == "pt" else "nome_en"
    blocos = []
    for d in contexto["macro"].values():
        # Taxa move em pontos percentuais; cotação, em porcentagem.
        if d["tipo"] == "taxa":
            delta = _delta(d.get("var_dia_abs"), idioma, t["pp"], escuro=True)
        else:
            delta = _delta(d.get("var_dia_pct"), idioma, escuro=True)

        blocos.append(
            '<div class="metric">'
            f'<div class="rot">{_esc(d[nome])}</div>'
            f'<div class="val">{_numero(d["valor"], d["casas"], idioma)}'
            f'<span class="un">{_esc(d["unidade"])}</span></div>'
            f'<div class="delta">{delta}</div>'
            f'<div class="ref">{_data(d["data"], idioma)}</div>'
            "</div>"
        )
    return f'<div class="metrics">{"".join(blocos)}</div>'


def _tabela_commodities(contexto, idioma, t):
    if not contexto["commodities"]:
        return f'<p class="vazio">{t["sem_dados"]}</p>'

    nome = "nome_pt" if idioma == "pt" else "nome_en"
    unidade = "unidade_pt" if idioma == "pt" else "unidade_en"

    linhas = []
    for d in contexto["commodities"].values():
        spark = _sparkline(d.get("serie", []), (d.get("var_mes_pct") or 0) >= 0)
        linhas.append(
            "<tr>"
            f'<td class="ativo">{_esc(d[nome])}</td>'
            f'<td>{_numero(d["valor"], 2, idioma)}'
            f'<span class="un-cell">{_esc(d[unidade])}</span></td>'
            f'<td>{_delta(d.get("var_dia_pct"), idioma)}</td>'
            f'<td>{_delta(d.get("var_semana_pct"), idioma)}</td>'
            f'<td>{_delta(d.get("var_mes_pct"), idioma)}</td>'
            f"<td>{spark}</td>"
            "</tr>"
        )

    return (
        '<div class="tbl-wrap"><table>'
        "<thead><tr>"
        f'<th>{t["col_ativo"]}</th><th>{t["col_valor"]}</th>'
        f'<th>{t["col_dia"]}</th><th>{t["col_semana"]}</th>'
        f'<th>{t["col_mes"]}</th><th>{t["col_tendencia"]}</th>'
        "</tr></thead>"
        f'<tbody>{"".join(linhas)}</tbody>'
        "</table></div>"
    )


def _bloco_noticias(contexto, t):
    noticias = contexto.get("noticias") or []
    if not noticias:
        return ""
    itens = []
    for n in noticias[: config.MAX_NOTICIAS_SITE]:
        quando = n["publicado"].strftime("%d/%m %H:%M") if n.get("publicado") else ""
        itens.append(
            "<li>"
            f'<a href="{_esc(n["link"])}" target="_blank" rel="noopener">'
            f'{_esc(n["titulo"])}</a>'
            f'<div class="meta">{_esc(n["fonte"])}'
            f'{" · " + quando if quando else ""}</div>'
            "</li>"
        )
    return (f'<section><h2>{t["secao_noticias"]}</h2>'
            f'<ul class="news">{"".join(itens)}</ul></section>')


